"""Record a training run's results in the committed ``experiments/`` folder, so runs made with
different code versions can be compared at the end.

    python tools/record_experiment.py --baselines                       # store baseline numbers once
    python tools/record_experiment.py --run runs/a2c_lin --name A2C_v1 --algo "A2C, symmetric critic" \
        --notes "entropy 1.0->0.05 over 20k"

For a run it evaluates ``best.pt`` on hsdpa/test, fcc/test and scenarios (deterministic test protocol),
then writes ``experiments/<name>/`` (config.json, train_log.csv, test_<set>.csv per-trace results) and
updates ``experiments/results.csv`` + ``experiments/README.md``.
"""

import argparse
import csv
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from abrsim import ABREnv, load_dataset  # noqa: E402
from evaluate import run_policy, write_csv  # noqa: E402

EXP = ROOT / "experiments"
TEST_SETS = {"hsdpa": "hsdpa/test", "fcc": "fcc/test", "scenarios": "scenarios"}
SCENARIOS = ["metro_tunnel", "stadium_crowd", "highway_handover", "flaky_wifi", "rural_edge"]
BASELINE_ORDER = ["Oracle", "RobustMPC", "BOLA", "RB", "BB", "FastMPC", "fixed_300"]


def summarize(per_trace, prefix):
    out = {}
    for key in ("qoe", "bitrate_mbps", "rebuffer_s", "switches"):
        out[f"{prefix}_{key}"] = round(float(np.mean([float(p[key]) for p in per_trace])), 4)
    if prefix == "scenarios":
        for sc in SCENARIOS:
            out[f"sc_{sc}"] = round(float(np.mean([float(p["qoe"]) for p in per_trace
                                                   if p["trace"].startswith(sc)])), 4)
    return out


def read_rows(path):
    with open(path) as f:
        return list(csv.DictReader(f))


def upsert(path, row, key="name"):
    rows = read_rows(path) if path.exists() else []
    rows = [r for r in rows if r[key] != row[key]] + [row]
    fields = list(dict.fromkeys(k for r in rows for k in r))
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)


def record_run(args):
    from agents import RLPolicy                       # needs torch
    run = Path(args.run)
    out = EXP / args.name
    out.mkdir(parents=True, exist_ok=True)
    shutil.copy(run / "config.json", out / "config.json")
    shutil.copy(run / "log.csv", out / "train_log.csv")

    log = read_rows(run / "log.csv")
    best = max(log, key=lambda r: float(r["val_qoe"]))
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True,
                            text=True).stdout.strip()
    row = {"name": args.name, "algo": args.algo, "notes": args.notes, "code_commit": commit,
           "iters": log[-1]["iter"],
           "train_time_min": round(float(log[-1]["time_s"]) / 60, 1),
           "best_val_iter": best["iter"], "best_val_qoe": round(float(best["val_qoe"]), 4)}
    for prefix, spec in TEST_SETS.items():
        traces = load_dataset(spec)
        env = ABREnv(traces, noise=False, random_start=False)
        _, per_trace = run_policy(RLPolicy.from_checkpoint(run / "best.pt", args.name), env, len(traces))
        write_csv(out / f"test_{prefix}.csv", per_trace)
        row |= summarize(per_trace, prefix)
        print(f"{args.name:12s} {spec:12s} QoE {row[f'{prefix}_qoe']:.3f}")
    upsert(EXP / "results.csv", row)


def record_baselines():
    for prefix, spec in TEST_SETS.items():
        src = ROOT / "results" / "baselines" / f"{spec.replace('/', '_')}_lin"
        for policy in BASELINE_ORDER:
            f = src / f"{policy}_traces.csv"
            if not f.exists():
                sys.exit(f"missing {f}: run `python evaluate.py --oracle --traces {spec}` first")
    for policy in BASELINE_ORDER:
        row = {"name": policy, "algo": "offline optimal (upper bound)" if policy == "Oracle" else "baseline"}
        for prefix, spec in TEST_SETS.items():
            src = ROOT / "results" / "baselines" / f"{spec.replace('/', '_')}_lin" / f"{policy}_traces.csv"
            row |= summarize(read_rows(src), prefix)
        upsert(EXP / "baselines.csv", row)
    print(f"stored {len(BASELINE_ORDER)} baselines in experiments/baselines.csv")


def write_readme():
    lines = ["# Experiments", "",
             "Generated by `tools/record_experiment.py`. Deterministic test protocol (see docs/08). "
             "QoE = mean per-chunk QoE_lin (higher is better); stall = rebuffer seconds per video.", ""]
    head = ("| Name | Algorithm | HSDPA QoE | HSDPA stall s | HSDPA switches | FCC QoE | Scenarios QoE | "
            "Tunnel | Stadium | Highway | Wi-Fi | Rural | Best val (iter) | Train min |")
    sep = "|" + "|".join(["---"] * (head.count("|") - 1)) + "|"
    lines += [head, sep]

    def fmt(r, k):
        return f"{float(r[k]):.3f}" if r.get(k) not in (None, "") else "–"

    rows = []
    if (EXP / "baselines.csv").exists():
        rows += [(r, True) for r in read_rows(EXP / "baselines.csv")]
    if (EXP / "results.csv").exists():
        rows += [(r, False) for r in read_rows(EXP / "results.csv")]
    for r, is_base in rows:
        name = f"*{r['name']}*" if is_base else f"**{r['name']}**"
        val = "" if is_base else f"{fmt(r, 'best_val_qoe')} ({r['best_val_iter']})"
        lines.append(" | ".join([
            f"| {name}", r["algo"], fmt(r, "hsdpa_qoe"), f"{float(r['hsdpa_rebuffer_s']):.2f}",
            f"{float(r['hsdpa_switches']):.1f}", fmt(r, "fcc_qoe"), fmt(r, "scenarios_qoe"),
            *[fmt(r, f"sc_{s}") for s in SCENARIOS], val, "" if is_base else r["train_time_min"]]) + " |")
    if (EXP / "results.csv").exists():
        lines += ["", "## Run notes", ""]
        lines += [f"- **{r['name']}** — {r['algo']} (code `{r.get('code_commit', '?')}`). {r['notes']}"
                  for r in read_rows(EXP / "results.csv")]
    (EXP / "README.md").write_text("\n".join(lines) + "\n")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--run", help="training run directory, e.g. runs/a2c_lin")
    p.add_argument("--name", help="short experiment name, e.g. A2C_v1")
    p.add_argument("--algo", default="")
    p.add_argument("--notes", default="")
    p.add_argument("--baselines", action="store_true", help="store baseline results from results/baselines/")
    args = p.parse_args()
    EXP.mkdir(exist_ok=True)
    if args.baselines:
        record_baselines()
    if args.run:
        if not args.name:
            p.error("--name is required with --run")
        record_run(args)
    write_readme()
    print("updated experiments/README.md")


if __name__ == "__main__":
    main()
